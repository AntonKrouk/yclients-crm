const OPERATOR_FILE = path.join(DATA_DIR, 'portal-operator.json');

const esc = (v) => String(v ?? '').replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));

function operator() {
  let o = {};
  try { o = JSON.parse(fs.readFileSync(OPERATOR_FILE, 'utf8')); } catch { /* шаблон не скопирован */ }
  const f = (k) => o[k] ? esc(o[k]) : '<mark>[уточняется]</mark>';
  return {
    name: f('name'), inn: f('inn'), ogrn: f('ogrn'), address: f('address'), email: f('email'), phone: f('phone'),
    line() { return `${this.name} (ИНН ${this.inn}, ОГРН ${this.ogrn}, адрес: ${this.address})`; },
    contacts() { return `электронная почта ${this.email}, телефон ${this.phone}, либо письменное заявление в любом из салонов`; },
  };
}

