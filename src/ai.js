// Ошибки YandexGPT приходят по-разному (иногда {error:{message}}, иногда {message}),
// а админу нужно человеческое объяснение — иначе он увидит «сервер ответил 401»
// и пойдёт с этим к Антону.
function explain(status, json) {
  const raw = json?.error?.message || json?.message || '';
  if (status === 401) return 'YandexGPT не принял ключ. Проверьте YC_API_KEY в .env';
  if (status === 403) return 'Нет доступа к YandexGPT: у сервисного аккаунта должна быть роль ai.languageModels.user, а у ключа — область yc.ai.languageModels.execute';
  if (status === 404) return 'YandexGPT не нашёл модель или каталог. Проверьте YC_FOLDER_ID в .env';
  if (status === 429) return 'YandexGPT сейчас ограничивает запросы — попробуйте через минуту';
  if (status >= 500) return 'YandexGPT временно недоступен — попробуйте позже';
  return raw ? `YandexGPT: ${raw}` : `YandexGPT ответил ${status}`;
}

// Диалог с моделью. history — вся переписка админа с ИИ по этому шаблону:
// [{role:'user'|'assistant', text}]. Отправляем её целиком каждый раз: у YandexGPT
// нет памяти между запросами, контекст живёт только в теле запроса.
// hint — необязательное название шаблона, помогает попасть в тему с первого раза.
const MAX_TURNS = 20;   // потолок на длину переписки

async function chat(history, hint = '') {
  if (!enabled()) throw new Error('ИИ не подключён: в .env нет YC_API_KEY или YC_FOLDER_ID');

  const turns = (Array.isArray(history) ? history : [])
    .filter(m => m && typeof m.text === 'string' && m.text.trim())
    .map(m => ({ role: m.role === 'assistant' ? 'assistant' : 'user', text: m.text.trim() }))
    .slice(-MAX_TURNS);   // при долгой правке важнее свежие реплики, чем самые первые
  if (!turns.length) throw new Error('Опишите, какое сообщение нужно');
  if (turns[turns.length - 1].role !== 'user') throw new Error('Последним должно быть сообщение администратора');

  // Название шаблона приклеиваем к ПЕРВОЙ реплике: дальше по ходу диалога оно уже
  // не нужно, а повторять его в каждом запросе — сбивать модель с текущей правки.
  if (hint && turns[0].role === 'user') {
    turns[0] = { role: 'user', text: `Название шаблона: ${hint}\nЗадача: ${turns[0].text}` };
  }

  const body = {
    modelUri: `gpt://${folderId()}/${model()}`,
    // Температура повыше намеренно: на 0.6 тексты выходили предсказуемо-пресными.
    completionOptions: { stream: false, temperature: 0.85, maxTokens: 900 },
    messages: [{ role: 'system', text: SYSTEM_PROMPT }, ...turns],
  };

  // Без таймаута зависший запрос держал бы кнопку «Сгенерировать» бесконечно
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), TIMEOUT_MS);
  let res, json;
  try {
    res = await fetch(API_URL, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Api-Key ${apiKey()}`,
        'x-folder-id': folderId(),
      },
      body: JSON.stringify(body),
      signal: ctrl.signal,
    });
    json = await res.json().catch(() => null);
  } catch (e) {
    if (e.name === 'AbortError') throw new Error('YandexGPT не ответил за 30 секунд — попробуйте ещё раз');
    throw new Error('Не удалось связаться с YandexGPT: ' + e.message);
  } finally {
    clearTimeout(timer);
  }

  if (!res.ok) throw new Error(explain(res.status, json));

  const out = json?.result?.alternatives?.[0]?.message?.text;
  if (!out || !out.trim()) throw new Error('YandexGPT вернул пустой ответ — переформулируйте задачу');

  // Модель иногда всё же предваряет текст служебной фразой или заворачивает его
  // в кавычки, хотя её просили этого не делать. Снимаем — админу нужен чистый текст,
  // который можно сразу отправить клиенту.
  const clean = out.trim()
    .replace(/^(?:вот\s+)?(?:исправленн?ый|обновлённ?ый|новый|другой)\s+вариант[:.]?\s*/i, '')
    .replace(/^[«"](.*)[»"]$/s, '$1')
    .trim();

  return { text: clean, usage: json?.result?.usage || null, model: model() };
}

module.exports = { enabled, chat };
